// Makes src/lib/worldMap.ts. Only needed if the map ever has to change.
// Copy this file into an empty folder, run there: npm i world-atlas@2 d3-geo@3 topojson-client@3, and
// write num2a2.json (ISO numeric -> two-letter code, e.g. from pycountry).
// Then, in that folder: node make-world-map.mjs . <panel>/src/lib/worldMap.ts
import fs from "node:fs";
import { geoEquirectangular, geoPath, geoCentroid, geoArea } from "d3-geo";
import { feature, mesh } from "topojson-client";
const topo = JSON.parse(fs.readFileSync(process.argv[2] + "/node_modules/world-atlas/countries-110m.json", "utf8"));
const num2a2 = JSON.parse(fs.readFileSync(process.argv[2] + "/num2a2.json", "utf8"));
const W = 1000, H = 440;
const all = feature(topo, topo.objects.countries);
all.features = all.features.filter((f) => f.properties.name !== "Antarctica");
const proj = geoEquirectangular().fitExtent([[0, 0], [W, H]], all);
const path = geoPath(proj).digits(1);
const land = path(all);
const borders = path(mesh(topo, topo.objects.countries, (a, b) => a !== b));
const centroids = {};
for (const f of all.features) {
  const a2 = num2a2[f.id];
  if (!a2) continue;
  // The dot goes on the country's biggest piece of land, so overseas land
  // (French Guiana, Alaska) does not pull France or the US out to sea.
  let shape = f;
  if (f.geometry.type === "MultiPolygon") {
    const parts = f.geometry.coordinates.map((c) => ({ type: "Feature", geometry: { type: "Polygon", coordinates: c } }));
    shape = parts.reduce((a, b) => (geoArea(b) > geoArea(a) ? b : a));
  }
  const [x, y] = proj(geoCentroid(shape));
  centroids[a2] = [Math.round(x * 10) / 10, Math.round(y * 10) / 10];
}
const box = (lon0, lat1, lon1, lat0) => { const [x0, y0] = proj([lon0, lat1]); const [x1, y1] = proj([lon1, lat0]); return [Math.round(x0), Math.round(y0), Math.round(x1 - x0), Math.round(y1 - y0)]; };
const views = { world: [0, 0, W, H], europe: box(-12, 62, 32, 35), westAfrica: box(-18.5, 17.5, -3, 9) };
// Kosovo and others without ISO numeric are skipped (listed under the map instead).
const out = `// GENERATED by scripts/make-world-map.mjs from world-atlas countries-110m
// (Natural Earth, public domain). Do not edit by hand. Drawn inside the panel:
// no outside map service is ever called.
export const MAP_WIDTH = ${W};
export const MAP_HEIGHT = ${H};
export const LAND = ${JSON.stringify(land)};
export const BORDERS = ${JSON.stringify(borders)};
/** Where to put each country's dot, by ISO two-letter code. */
/** viewBox (x, y, width, height) for each zoom button. */
export const VIEWS = ${JSON.stringify(views)} as const;
export const CENTROIDS: Record<string, [number, number]> = ${JSON.stringify(centroids)};
`;
fs.writeFileSync(process.argv[3], out);
console.log(Object.keys(centroids).length, (out.length/1024).toFixed(0)+"KB", centroids.GM, centroids.SN, centroids.GB);
